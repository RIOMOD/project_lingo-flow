export function renderNavIcon(label, defaultIcon) {
  const lower = (label || "").toLowerCase();
  
  if (lower.includes("tổng quan") || lower.includes("dashboard")) return <IconDashboard />;
  if (lower.includes("người dùng") || lower.includes("học viên")) return <IconUsers />;
  if (lower.includes("giảng viên") || lower.includes("teacher")) return <IconTeacher />;
  if (lower.includes("phân quyền") || lower.includes("roles")) return <IconRoles />;
  if (lower.includes("hoạt động") || lower.includes("hệ thống") || lower.includes("activity")) return <IconActivity />;
  
  if (lower.includes("duyệt khóa học") || lower.includes("approval")) return <IconApproval />;
  if (lower.includes("xuất bản") || lower.includes("publish")) return <IconPublish />;
  if (lower.includes("khóa học") || lower.includes("nội dung")) return <IconCourses />;
  if (lower.includes("lộ trình") || lower.includes("path")) return <IconPath />;
  
  if (lower.includes("đơn hàng") || lower.includes("orders")) return <IconOrders />;
  if (lower.includes("giao dịch") || lower.includes("transactions")) return <IconTransactions />;
  if (lower.includes("mã giảm giá") || lower.includes("coupons")) return <IconCoupons />;
  if (lower.includes("hoàn tiền") || lower.includes("refunds")) return <IconRefunds />;
  if (lower.includes("báo cáo") || lower.includes("tiến độ") || lower.includes("reports")) return <IconReports />;

  if (lower.includes("bài tập")) return <IconExercise />;
  if (lower.includes("kiểm tra") || lower.includes("test")) return <IconTest />;
  if (lower.includes("từ vựng")) return <IconVocab />;
  if (lower.includes("ngữ pháp")) return <IconGrammar />;
  if (lower.includes("chatbot") || lower.includes("ai")) return <IconBot />;
  if (lower.includes("writing") || lower.includes("sửa")) return <IconWriting />;
  if (lower.includes("cài đặt") || lower.includes("quản trị") || lower.includes("vận hành")) return <IconSettings />;
  
  return <IconDashboard />;
}
